#!/usr/bin/env bash
# 修完之后的完整复验：四个场景一次跑完，每一步都对着真实硬件。
#
#   ① 开机诊断   → [BOOT] reason=N / prev:  —— 设备上一次是怎么结束的
#   ② 连断循环   → 连上、断开、再扫到（"蓝牙不稳"）
#   ③ 大段 ME    → 发 5KB 中文，看主循环有没有被按住（"发文本崩溃"）
#   ④ 三现象回归 → 连接拉配置 / 发 ME 时主循环存活 / 断开后能重扫
#
# 用法: tools/verify_all.sh [设备地址前缀]
#   不给前缀就自动挑第一块能连上的板子。
set -u

DIR="/Users/yanyouqiang/project/my-mx9.0/archives/6.0/lvgl_s3"
ADDR="${1:-}"
cd "$DIR" || exit 1

A=()
[ -n "$ADDR" ] && A=(--addr "$ADDR")

echo "############################################################"
echo "# ① 开机诊断：上一次是怎么结束的"
echo "############################################################"
/usr/bin/python3 tools/boot_reason.py ${ADDR:+"$ADDR"} 2>&1 | head -30

echo
echo "############################################################"
echo "# ② 连断循环：断开后还能不能被重新扫到"
echo "############################################################"
/usr/bin/python3 tools/ble_cycle.py 5 12 ${ADDR:+"$ADDR"} 2>&1 | tail -25

echo
echo "############################################################"
echo "# ③ 大段 ME（5KB 中文）：主循环会不会被按住"
echo "############################################################"
/usr/bin/python3 tools/ble_stress.py --only me "${A[@]}" 2>&1 | tail -25

echo
echo "############################################################"
echo "# ④ 三现象回归"
echo "############################################################"
/usr/bin/python3 tools/verify_fix.py 2>&1 | tail -55
